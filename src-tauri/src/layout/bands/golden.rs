// 모양에서 지은 칸 · 분할 id 의 시작 — 이 파일의 배치들이 쓰는 id 와 겹치지 않는다.
const SHAPE_ID_BASE: u128 = 0xD0C0_0000_0000;

fn parse_shape(shape: &str) -> LayoutNode {
    fn node(rest: &mut &str, next: &mut u128) -> LayoutNode {
        let mut fresh = || {
            *next += 1;
            Uuid::from_u128(SHAPE_ID_BASE + *next)
        };
        let (head, tail) = rest.split_at(1);
        match head {
            "l" => {
                *rest = tail;
                LayoutNode::Slot {
                    id: fresh(),
                    content: SlotContent::Empty,
                }
            }
            "h" | "v" => {
                let (ratio, after) = tail.split_once('_').expect("비율 뒤 `_`");
                *rest = after;
                let split_id = fresh();
                let a = node(rest, next);
                let b = node(rest, next);
                LayoutNode::Split {
                    id: split_id,
                    dir: if head == "h" {
                        SplitDir::LeftRight
                    } else {
                        SplitDir::TopBottom
                    },
                    ratio: ratio.parse().expect("비율"),
                    a: Box::new(a),
                    b: Box::new(b),
                }
            }
            other => panic!("모양 문자 {other:?}"),
        }
    }
    let mut rest = shape;
    let mut next = 0;
    let tree = node(&mut rest, &mut next);
    assert!(rest.is_empty(), "모양 {shape:?} 뒤에 남은 것 {rest:?}");
    tree
}

// 비율 = JS `String(n)` 과 같은 최단 왕복 표기 — 분할 비율(`RATIO_MIN..=RATIO_MAX`)에서는 Rust `Display` 와 같다.
fn encode_shape(node: &LayoutNode) -> String {
    match node {
        LayoutNode::Slot { .. } => "l".to_owned(),
        LayoutNode::Split {
            dir, ratio, a, b, ..
        } => {
            let d = match dir {
                SplitDir::LeftRight => "h",
                SplitDir::TopBottom => "v",
            };
            format!("{d}{ratio}_{}{}", encode_shape(a), encode_shape(b))
        }
    }
}

