/// 창 하나를 지금 규칙으로 돌린 것.
struct Eval<'a> {
    targets: WindowTargets<'a>,
    bands: Vec<BandHit>,
    frames: Vec<(Uuid, PxRect)>,
}

impl<'a> Eval<'a> {
    fn new(input: &'a BandsInput, incoming: &'a LayoutNode) -> Self {
        let canvas = CanvasPx {
            w: input.canvas.w,
            h: input.canvas.h,
        };
        let targets = WindowTargets {
            canvas,
            layout: &input.layout,
            incoming,
            original: input.original.map_or(
                SizeCss {
                    w: f64::NAN,
                    h: f64::NAN,
                },
                SizeCss::from,
            ),
            zone: input
                .tab_bar
                .map(|area| zone_in_canvas(strip_zone(area), input.canvas_origin)),
        };
        let bands = effective_bands(&targets);
        let frames = frames(&input.layout, canvas);
        Eval {
            targets,
            bands,
            frames,
        }
    }

    fn zone(&self) -> Option<RectCss> {
        self.targets.zone
    }

    fn blocked(&self) -> Vec<BlockedLine> {
        let t = &self.targets;
        let whole = PxRect {
            x0: 0,
            y0: 0,
            x1: t.canvas.w,
            y1: t.canvas.h,
        };
        std::iter::once((DockAnchor::Outer, whole))
            .chain(
                self.frames
                    .iter()
                    .map(|(id, frame)| (DockAnchor::Slot(*id), *frame)),
            )
            .flat_map(|(anchor, target)| SIDE_ORDER.map(|side| (anchor, side, target)))
            .filter(|&(anchor, side, target)| {
                let share = attach_share(t.original, side, target);
                landing_rect(t.layout, anchor, side, t.incoming, t.canvas, share).is_none()
            })
            .map(|(anchor, side, _)| BlockedLine {
                anchor: anchor_json(anchor),
                side,
            })
            .collect()
    }

    fn bands(&self) -> Vec<BandLine> {
        self.bands
            .iter()
            .map(|b| BandLine {
                anchor: anchor_json(b.anchor),
                side: b.side,
                band: b.band.into(),
                areas: b.areas.iter().map(|a| (*a).into()).collect(),
                share: b.share,
                landing: b.landing.into(),
            })
            .collect()
    }

    // 그 칸 위에서 그릴 구역 선 — `slot_zones` 가 점마다 내는 값과 같아야 한다(`point` 가 견준다).
    fn zones_of(&self, slot: Uuid, frame: PxRect) -> Option<SlotZones> {
        self.bands
            .iter()
            .any(|b| b.anchor == DockAnchor::Slot(slot))
            .then(|| {
                let room = band_frame(frame, self.targets.canvas, &outer_sides(&self.bands));
                SlotZones {
                    slot: room,
                    centre: slot_centre(frame, room),
                }
            })
    }

    fn slots(&self) -> Vec<SlotLine> {
        self.frames
            .iter()
            .map(|&(id, frame)| SlotLine {
                id,
                frame: frame.into(),
                zones: self.zones_of(id, frame).map(ZonesLine::from),
            })
            .collect()
    }

    fn point(&self, x: f64, y: f64) -> (Value, Value) {
        let p = PointCss { x, y };
        if self.targets.zone.is_some_and(|z| contains(&z, p)) {
            return (json!("strip"), Value::Null);
        }
        let pick = json!(choose(&self.bands, p));
        let Some(drawn) = slot_zones(&self.targets, &self.bands, p) else {
            return (pick, Value::Null);
        };
        let (slot, frame) = frame_at(self.targets.layout, self.targets.canvas, p)
            .expect("선을 그린 점 = 캔버스 안");
        assert_eq!(self.zones_of(slot, frame), Some(drawn), "{p:?}");
        let at = self.frames.iter().position(|(s, _)| *s == slot).unwrap();
        (pick, json!(at))
    }
}

fn drag_size_line(input: &DragSizeInput) -> DragSizeLine<'_> {
    let out = drag_sizes(&SourceWindow {
        restored: input.restored.map(SizeCss::from),
        maximized: input.maximized,
        insets: input.insets,
        viewport: input.viewport.into(),
        work: input.work.into(),
        chrome: input.chrome.into(),
        single: input.single,
    });
    DragSizeLine {
        input,
        size: out.size.map(Size::from),
        original: out.original.into(),
    }
}

