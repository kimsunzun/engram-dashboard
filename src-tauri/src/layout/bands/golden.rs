// 점을 4 분의 1 px 격자에 — 이진 소수라 JSON 왕복 · TS 셈이 정확하다.
fn quarter(v: f64) -> f64 {
    (v * 4.0).round() / 4.0
}

/// 점 고르기 — 캔버스를 조금 넘는 성긴 격자 + 띠 영역 · 탭바 구역의 변 안팎 + 칸 구역 선의 대각선 가운데 · 가운데.
fn probe_points(e: &Eval) -> Vec<(f64, f64)> {
    let (w, h) = (f64::from(e.targets.canvas.w), f64::from(e.targets.canvas.h));
    let mut pts: Vec<(f64, f64)> = Vec::new();
    for i in 0..=12 {
        for j in 0..=9 {
            pts.push((
                quarter(-3.0 + f64::from(i) * (w + 6.0) / 12.0),
                quarter(-20.0 + f64::from(j) * (h + 23.0) / 9.0),
            ));
        }
    }
    let mut edges = |x0: f64, y0: f64, x1: f64, y1: f64| {
        let (mx, my) = (quarter((x0 + x1) / 2.0), quarter((y0 + y1) / 2.0));
        for (x, y) in [
            (x0, my),
            (x0 - 0.25, my),
            (x1 - 0.25, my),
            (x1, my),
            (mx, y0),
            (mx, y0 - 0.25),
            (mx, y1 - 0.25),
            (mx, y1),
        ] {
            pts.push((quarter(x), quarter(y)));
        }
    };
    for b in &e.bands {
        for a in &b.areas {
            edges(
                f64::from(a.x0),
                f64::from(a.y0),
                f64::from(a.x1),
                f64::from(a.y1),
            );
        }
    }
    if let Some(z) = e.targets.zone {
        edges(z.x0.max(0.0), z.y0.max(-20.0), z.x1, z.y1);
    }
    for &(slot, frame) in &e.frames {
        let Some(z) = e.zones_of(slot, frame) else {
            continue;
        };
        let (r, c) = (z.slot, z.centre);
        let (rx0, ry0, rx1, ry1) = (
            f64::from(r.x0),
            f64::from(r.y0),
            f64::from(r.x1),
            f64::from(r.y1),
        );
        for (x, y) in [
            ((rx0 + c.x0) / 2.0, (ry0 + c.y0) / 2.0),
            ((rx1 + c.x1) / 2.0, (ry0 + c.y0) / 2.0),
            ((rx0 + c.x0) / 2.0, (ry1 + c.y1) / 2.0),
            ((rx1 + c.x1) / 2.0, (ry1 + c.y1) / 2.0),
            ((c.x0 + c.x1) / 2.0, (c.y0 + c.y1) / 2.0),
        ] {
            pts.push((quarter(x), quarter(y)));
        }
    }
    let mut keyed: Vec<((i64, i64), (f64, f64))> = pts
        .into_iter()
        .map(|(x, y)| (((y * 4.0) as i64, (x * 4.0) as i64), (x, y)))
        .collect();
    keyed.sort_by_key(|(k, _)| *k);
    keyed.dedup_by_key(|(k, _)| *k);
    keyed.into_iter().map(|(_, p)| p).collect()
}

fn line(v: &impl Serialize) -> String {
    serde_json::to_string(v).expect("직렬화")
}

// `"key": [` 한 줄 · 원소마다 한 줄 · `]` — 비면 `"key": []`.
fn push_list(out: &mut String, indent: &str, key: &str, items: &[String], last: bool) {
    let comma = if last { "" } else { "," };
    if items.is_empty() {
        let _ = writeln!(out, "{indent}\"{key}\": []{comma}");
        return;
    }
    let _ = writeln!(out, "{indent}\"{key}\": [");
    for (i, item) in items.iter().enumerate() {
        let sep = if i + 1 == items.len() { "" } else { "," };
        let _ = writeln!(out, "{indent}  {item}{sep}");
    }
    let _ = writeln!(out, "{indent}]{comma}");
}

fn render_golden() -> String {
    let mut out = String::from("{\n");
    let _ = writeln!(out, "  \"_format\": {},", line(&FORMAT));
    let _ = writeln!(out, "  \"_constants\": {},", line(&current_constants()));
    let _ = writeln!(out, "  \"ratio_limits\": {},", line(&RATIO_LIMITS));
    let _ = writeln!(out, "  \"bands\": [");
    let inputs = band_inputs();
    for (n, input) in inputs.iter().enumerate() {
        let incoming = parse_shape(&input.shape);
        let e = Eval::new(input, &incoming);
        let _ = writeln!(out, "    {{");
        for (key, v) in [
            ("name", line(&input.name)),
            ("canvas", line(&input.canvas)),
            ("canvas_origin", line(&input.canvas_origin)),
            ("tab_bar", line(&input.tab_bar)),
            ("layout", line(&input.layout)),
            ("shape", line(&input.shape)),
            ("original", line(&input.original)),
            ("zone", line(&e.zone())),
        ] {
            let _ = writeln!(out, "      \"{key}\": {v},");
        }
        fn lines<T: Serialize>(vs: Vec<T>) -> Vec<String> {
            vs.iter().map(line).collect()
        }
        push_list(&mut out, "      ", "blocked", &lines(e.blocked()), false);
        push_list(&mut out, "      ", "bands", &lines(e.bands()), false);
        push_list(&mut out, "      ", "slots", &lines(e.slots()), false);
        let points: Vec<String> = probe_points(&e)
            .into_iter()
            .map(|(x, y)| {
                let (pick, zones) = e.point(x, y);
                line(&(x, y, pick, zones))
            })
            .collect();
        push_list(&mut out, "      ", "points", &points, true);
        let sep = if n + 1 == inputs.len() { "" } else { "," };
        let _ = writeln!(out, "    }}{sep}");
    }
    let _ = writeln!(out, "  ],");
    let sizes: Vec<String> = drag_size_inputs()
        .iter()
        .map(|input| line(&drag_size_line(input)))
        .collect();
    push_list(&mut out, "  ", "drag_size", &sizes, true);
    out.push_str("}\n");
    out
}

#[test]
#[ignore = "골든을 다시 뜬다 — 규칙을 일부러 바꿨을 때만 돌린다"]
fn regenerate_bands_golden() {
    let text = render_golden();
    assert_eq!(text, render_golden(), "두 번 뜨면 같은 바이트");
    let parsed: Value = serde_json::from_str(&text).expect("뜬 골든은 JSON");
    assert!(parsed["bands"].as_array().is_some_and(|b| !b.is_empty()));
    let path =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src/layout/bands_golden.json");
    std::fs::write(path, text).expect("골든 쓰기");
}
