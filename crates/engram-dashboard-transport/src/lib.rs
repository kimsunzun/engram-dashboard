//!   막으려면 잊은 것을 기억해야 하고, 그러면 상한을 두는 이유가 사라진다.
//! - ★**재연결 예산은 축이 둘이다**★ — 「못 붙는다」(연결 성공이 0 으로 되돌린다)와 「붙어도 안
