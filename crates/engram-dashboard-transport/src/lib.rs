//!   건네므로 닫기 **코드와 문구가 커널을 건너오나**는 값 전달로 안 재진다 — 어댑터의 성질이다. 사유의
//!   정본은 `tests/ws_reject.rs` 헤더이고, ★이 스위트는 위 열거 밖이라 결정 기록이 아직 없다★.
//! ★그 셋을 「인메모리 하네스로 옮기면 빨라진다」로 읽지 말 것★ — 옮기는 순간 재던 것이 사라진다.
