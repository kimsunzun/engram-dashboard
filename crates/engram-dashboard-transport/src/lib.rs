//!   잘림이 된다.
//! - ★**창 시한이 쓰기 도중 지나고 그 사이 재생분이 앞잡이 줄에 들어왔으면 그 재생분은 창에 못 닿는다 — 배압이
//!   없어도**★ — 운영 루프는 시한이 지났으면 프레임보다 타이머를 먼저 본다(`peer.rs` 의 `next_turn`). 쓰기가 끝난
