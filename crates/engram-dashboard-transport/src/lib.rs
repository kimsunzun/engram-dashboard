//!   순서대로 내보내면서** 그 번호를 올린다. 그래서 값이 참이다 — 실제로 그 번호부터 배달한다. 진도는 붙든 것의
//!   끝 번호까지 밀어, 늦게 온 재생분이 내보낸 번호를 다시 올리지 않는다. 상대의 권위 값(우리 wire 의
//!   `SubscribeAck.oldest_seq`)을 쓰려면 `Wire` 에 칸이 하나 늘어야 하고, ★그건 소비자 전부를 깨는
