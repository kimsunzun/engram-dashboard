//! failure — 「마지막 실패」의 종류 어휘.
//!
//! ★거처(ADR-0168 두 질문의 답)★: 누가 봐야 하나 = 모든 창 + 제어 LLM(→ 프론트 저장소로는 못 나른다) ·
//!   언제까지 살아야 하나 = 데몬이 사는 동안(→ 디스크에 두지 않는다). 그래서 이 값은 프로필 구조체의
//!   **메모리 전용 필드**로 산다(`AgentProfile::last_failure`).
//!
//! ★이 모듈은 어휘만 소유한다★: 무엇이 실패인지 관측하고 기록·지움을 집행하는 것은
//!   `manager::AgentManager::note_activation_result` 하나뿐이고, 프로그램별 출력에서 원인을 알아보는 것은
//!   `backend` 몫이다. 종류 → {다시 해볼 가치 · 문구 · 권하는 행동} 표는 그 값을 실제로 소비하는 쪽
//!   (프론트 `src/components/agent/failureKinds.ts`)이 진다 — 여기 두 번째 표를 만들지 말 것.
//!
//! tauri import 0 — 격리 규칙 준수.
// ADR-0168
// ADR-0169

/// 활성화가 실패한 종류.
///
/// ★지금 상태(`AgentStatus`)와 **별개 축**이다 — 합치지 말 것★: 합치면 "도는 중인데 마지막 실패를 든"
///   조합이 표현되지 않고, 그 조합이 없으면 화면의 「도는 중이 이긴다」 규칙도 설 자리가 없다
///   (ADR-0169 결정 3 · ADR-0170).
/// ★serde 파생을 일부러 달지 않았다 — 되살리지 마라★: 이 값은 디스크에 나가면 안 된다(ADR-0169 결정 2).
///   프로필 필드가 `#[serde(skip)]` 이라 지금도 안 나가지만, 파생이 없으면 그 skip 을 지우는 변경이
///   **컴파일 에러**가 된다. 통신 규격으로 나가는 미러는 `protocol::AgentFailureKind` 가 따로 진다.
/// ★「다시 해볼 가치가 있나」 판정을 여기 두지 않는다★: 지금 그 값을 읽는 소비자는 화면뿐이고
///   (클릭 차단·「새 대화로 시작」은 후속), 통신 규격은 종류만 나른다. 양쪽에 표를 두면 컴파일러가
///   맞춰 주지 못하는 사본이 둘 생긴다 — 소비자가 코어로 오면 그때 이리로 옮긴다.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AgentFailureKind {
    /// 이어받을 대화 실물이 없다 — 우리가 발급한 식별자로 대화가 만들어진 적이 없다(한 마디도 주고받지
    /// 않고 죽은 항목). 같은 식별자로 다시 시도해도 결과가 같다.
    NoConversationToResume,
    /// 프로세스를 띄우지 못했다(실행파일 부재·권한·일시적 자원 부족 등).
    SpawnFailed,
    /// 이어받기로 떴으나 관측 창 안에 종료했다 — 위 갈래로 알아보지 못한 나머지 전부.
    EarlyExitAfterResume,
    /// 어느 갈래로도 분류되지 않았다.
    Other,
}
